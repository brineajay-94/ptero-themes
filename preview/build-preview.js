#!/usr/bin/env node
/**
 * brine-theme preview builder.
 *
 * Regenerates the generated parts of preview/ from a real Pterodactyl checkout:
 *
 *   preview/icons.js                 inline SVG paths (FontAwesome free-solid)
 *   preview/panel-preview.css        Tailwind build of panel-preview.source.css
 *   preview/fonts/*.woff2            Montserrat + Playfair Display variable fonts
 *
 * Usage:
 *
 *   node preview/build-preview.js --panel /var/www/pterodactyl
 *
 * The panel directory only needs its node_modules installed (yarn install) and
 * its original public/themes tree - no database, no built assets.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const PREVIEW_DIR = __dirname;
const THEME_DIR = path.resolve(PREVIEW_DIR, "..", "theme");

